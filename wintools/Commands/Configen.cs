using System.Globalization;
using System.Runtime.CompilerServices;
using System.Text;
using System.Xml;
using System.Xml.Linq;

namespace WinTools;

// configen (theappbusiness/ConfigGenerator): turns a property list of settings plus a mapping
// ("hints") file of `name : Type` lines into a Swift class, or an Objective-C .h/.m pair, with one
// constant per setting. Pure text generation, so it runs the same as on macOS.
static class Configen
{
    [ModuleInitializer]
    internal static void Register() =>
        Commands.Add("configen", "Generate a Swift or Objective-C config class from a plist", Run);

    const string Usage = """
        Usage: configen -p <plist> -h <hints> -n <class name> -o <output directory> [-c]
          -p, --plist-path        Path to the input plist file
          -h, --hints-path        Path to the mapping file (one "name : Type" per line)
          -n, --class-name        The output config class name
          -o, --output-directory  The output config class directory
          -c, --objective-c       Generate an Objective-C .h/.m pair instead of Swift
        """;

    static int Run(string[] args)
    {
        string plistPath = null, hintsPath = null, className = null, outDir = null;
        var objc = false;
        for (var i = 0; i < args.Length; i++)
        {
            string Value() => i + 1 < args.Length ? args[++i] : throw new UsageException($"{args[i]} needs a value");
            switch (args[i])
            {
                case "--help": Console.WriteLine(Usage); return 0;
                case "--version": Console.WriteLine("configen 1.1.2"); return 0;
                case "-p" or "--plist-path": plistPath = Value(); break;
                case "-h" or "--hints-path": hintsPath = Value(); break;
                case "-n" or "--class-name": className = Value(); break;
                case "-o" or "--output-directory": outDir = Value(); break;
                case "-c" or "--objective-c": objc = true; break;
                default: throw new UsageException($"unknown option {args[i]} (see configen --help)");
            }
        }
        if (plistPath == null || hintsPath == null || className == null || outDir == null)
            throw new UsageException("-p, -h, -n and -o are all required (see configen --help)");

        var plist = ReadPlist(plistPath);
        var hints = new List<(string Name, string Type)>();
        foreach (var raw in File.ReadAllLines(hintsPath))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line.StartsWith("//") || line.StartsWith('#')) continue;
            var colon = line.IndexOf(':');
            if (colon < 0) throw new InvalidOperationException($"{hintsPath}: expected \"name : Type\", got \"{line}\"");
            hints.Add((line[..colon].Trim(), line[(colon + 1)..].Trim()));
        }
        foreach (var (name, _) in hints)
            if (!plist.ContainsKey(name)) throw new InvalidOperationException($"{plistPath}: missing key \"{name}\" from the mapping file");

        Directory.CreateDirectory(outDir);
        var header = $"// auto-generated by configen\n// to add or remove properties, edit the mapping file: '{hintsPath}'.\n// README: https://github.com/theappbusiness/ConfigGenerator/blob/master/README.md\n\n";
        if (objc)
        {
            var h = new StringBuilder(header).Append("#import <Foundation/Foundation.h>\n\n").Append($"@interface {className} : NSObject\n\n");
            var m = new StringBuilder(header).Append($"#import \"{className}.h\"\n\n@implementation {className}\n\n");
            foreach (var (name, type) in hints)
            {
                var (decl, expr) = ObjcValue(name, type, plist[name]);
                h.Append($"+ ({decl}){name};\n");
                m.Append($"+ ({decl}){name}\n{{\n  return {expr};\n}}\n\n");
            }
            h.Append("\n@end\n");
            m.Append("@end\n");
            File.WriteAllText(Path.Combine(outDir, className + ".h"), h.ToString());
            File.WriteAllText(Path.Combine(outDir, className + ".m"), m.ToString());
        }
        else
        {
            var s = new StringBuilder(header).Append("import Foundation\n\n").Append($"public class {className} {{\n\n");
            foreach (var (name, type) in hints)
                s.Append($"  public static let {name}: {type} = {SwiftValue(name, type, plist[name])}\n");
            s.Append("\n}\n");
            File.WriteAllText(Path.Combine(outDir, className + ".swift"), s.ToString());
        }
        return 0;
    }

    static string SwiftValue(string name, string type, XElement v)
    {
        switch (type)
        {
            case "String": return Quote(Str(name, v));
            case "URL": return $"URL(string: {Quote(Str(name, v))})!";
            case "Int": return Num(name, v, integer: true);
            case "Double" or "Float" or "CGFloat" or "TimeInterval": return Num(name, v, integer: false);
            case "Bool": return BoolValue(name, v) ? "true" : "false";
            default:
                if (type.StartsWith('[')) return SwiftLiteral(v);
                // Custom types are built from the raw plist value, like configen does.
                return $"{type}({SwiftLiteral(v)})";
        }
    }

    static string SwiftLiteral(XElement v) => v.Name.LocalName switch
    {
        "string" or "date" => Quote(v.Value),
        "integer" or "real" => v.Value.Trim(),
        "true" => "true",
        "false" => "false",
        "array" => "[" + string.Join(", ", v.Elements().Select(SwiftLiteral)) + "]",
        "dict" => DictPairs(v) is var pairs && pairs.Count == 0 ? "[:]"
            : "[" + string.Join(", ", pairs.Select(p => $"{Quote(p.Key)}: {SwiftLiteral(p.Value)}")) + "]",
        _ => Quote(v.Value),
    };

    static (string Decl, string Expr) ObjcValue(string name, string type, XElement v) => type.TrimEnd('*', ' ') switch
    {
        "NSString" or "String" => ("NSString *", "@" + Quote(Str(name, v))),
        "NSURL" or "URL" => ("NSURL *", $"[NSURL URLWithString:@{Quote(Str(name, v))}]"),
        "NSInteger" or "Int" or "int" => ("NSInteger", Num(name, v, integer: true)),
        "double" or "Double" or "CGFloat" or "float" or "NSTimeInterval" => (type, Num(name, v, integer: false)),
        "BOOL" or "Bool" => ("BOOL", BoolValue(name, v) ? "YES" : "NO"),
        "NSArray" or "NSDictionary" or "NSNumber" => (type.TrimEnd('*', ' ') + " *", ObjcLiteral(v)),
        _ => throw new InvalidOperationException($"unsupported Objective-C type \"{type}\" for {name}"),
    };

    static string ObjcLiteral(XElement v) => v.Name.LocalName switch
    {
        "integer" or "real" => "@" + v.Value.Trim(),
        "true" => "@YES",
        "false" => "@NO",
        "array" => "@[" + string.Join(", ", v.Elements().Select(ObjcLiteral)) + "]",
        "dict" => "@{" + string.Join(", ", DictPairs(v).Select(p => $"@{Quote(p.Key)}: {ObjcLiteral(p.Value)}")) + "}",
        _ => "@" + Quote(v.Value),
    };

    static string Str(string name, XElement v) =>
        v.Name.LocalName == "string" ? v.Value : throw new InvalidOperationException($"{name}: expected a string in the plist, found <{v.Name.LocalName}>");

    static string Num(string name, XElement v, bool integer)
    {
        var text = v.Value.Trim();
        if (v.Name.LocalName is not ("integer" or "real" or "string") ||
            !double.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out var d))
            throw new InvalidOperationException($"{name}: expected a number in the plist");
        if (integer && d != Math.Floor(d)) throw new InvalidOperationException($"{name}: expected an integer in the plist");
        return integer ? ((long)d).ToString(CultureInfo.InvariantCulture) : text;
    }

    static bool BoolValue(string name, XElement v) => v.Name.LocalName switch
    {
        "true" => true,
        "false" => false,
        "string" when bool.TryParse(v.Value.Trim(), out var b) => b,
        _ => throw new InvalidOperationException($"{name}: expected a boolean in the plist"),
    };

    static string Quote(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n") + "\"";

    static List<KeyValuePair<string, XElement>> DictPairs(XElement dict)
    {
        var pairs = new List<KeyValuePair<string, XElement>>();
        string key = null;
        foreach (var e in dict.Elements())
        {
            if (e.Name.LocalName == "key") key = e.Value;
            else if (key != null) { pairs.Add(new(key, e)); key = null; }
        }
        return pairs;
    }

    static Dictionary<string, XElement> ReadPlist(string path)
    {
        XDocument doc;
        try
        {
            using var reader = XmlReader.Create(path, new XmlReaderSettings { DtdProcessing = DtdProcessing.Ignore, XmlResolver = null });
            doc = XDocument.Load(reader);
        }
        catch (XmlException e) { throw new InvalidOperationException($"{path}: not an XML property list ({e.Message})"); }
        var dict = doc.Root?.Element("dict") ?? throw new InvalidOperationException($"{path}: plist has no top-level <dict>");
        return DictPairs(dict).ToDictionary(p => p.Key, p => p.Value);
    }
}
