class Scdoc < Formula
  desc "Small man page generator"
  homepage "https://sr.ht/~sircmpwn/scdoc/"
  url "https://repo.msys2.org/mingw/ucrt64/mingw-w64-ucrt-x86_64-scdoc-1.11.4-1-any.pkg.tar.zst"
  sha256 "8dadc7cd17f2cbd0e162a470d19eb4996e2a67acf21ea40d864c8c10bd39aa9b"
  license "MIT"

  # Prebuilt UCRT64 package from MSYS2; its runtime packages are pinned as resources.

  livecheck do
    url "https://git.sr.ht/~sircmpwn/scdoc/archive/1.11.5.tar.gz"
  end

  def install
    msys2_install
    msys2_bin "ucrt64/bin/scdoc.exe", "scdoc"
  end

  test do
    preamble = <<~EOF
      .\\" Generated by scdoc #{version}
      .\\" Complete documentation for this program is not available as a GNU info page
      .ie \\n(.g .ds Aq \\(aq
      .el       .ds Aq '
      .nh
      .ad l
      .\\" Begin generated content:
    EOF
    assert_equal preamble, pipe_output(bin/"scdoc", "")
  end
end
